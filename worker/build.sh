#!/bin/sh
# Cloudflare Workers Builds 가 배포 전에 부르는 명령입니다.
#
# **검사를 안 거친 코드가 나가면 안 됩니다.** PyPI 쪽은 태그를 붙일 때 검사를
# 먼저 돌리는데, Git 연동은 밀기만 하면 배포되기 때문에 여기서 막습니다.
# 0 이 아닌 값을 돌려주면 배포가 멈춥니다.
#
# 셸 변수 이름은 **영문만** 씁니다. 한글로 썼더니 `command not found` 가 났고,
# 워크플로 작업 ID 를 한글로 써서 조용히 안 돌았던 E33 과 같은 자리입니다.
set -eu

fail() { echo "  ✗ $1"; exit 1; }
need() { grep -q "$1" worker.js || fail "$2"; echo "  ✓ $2"; }

echo "── 워커 배포 전 검사 ──"

node --check worker.js || fail "문법 오류"
echo "  ✓ 문법"

# 자유 텍스트를 받기 시작하면 그 순간 경로·키가 새어 들어옵니다(E8).
# **있는지가 아니라 거르는지를 봅니다.** 있는지만 보면 규칙을 망가뜨려도
# 그 줄은 그대로라 통과합니다 — E10 입니다.
node test.mjs || fail "열쇠 규칙이 제대로 안 거른다"

# 무료 한도를 자기 설정으로 태우는 것이 우리 사고 E13 입니다.
need '무료_KV쓰기_하루' "무료 한도 방어가 있다"

# 늦게 반영되는 저장소에서 읽고 고쳐 쓰면 남의 숫자를 덮어씁니다(E3).
# `grep -c` 는 **줄 수**를 셉니다. 한 줄에 두 번 쓰면 1 로 나와서 그냥 통과합니다 —
# 실제로 그렇게 만들어 봤더니 검사가 헛돌았습니다(E10). 나온 횟수를 셉니다.
writes=$(grep -o 'env\.KV\.put' worker.js | wc -l | tr -d ' ')
[ "$writes" -le 1 ] || fail "KV 쓰기가 ${writes}곳 — 덧쓰기 하나여야 한다"
echo "  ✓ 덧쓰기만 한다 (쓰기 ${writes}곳)"

# 사람 수를 따로 세야 카탈로그의 근거가 자랍니다.
need '사람\[사고\]' "사람 수를 따로 센다"

echo "전부 통과. 배포합니다."
